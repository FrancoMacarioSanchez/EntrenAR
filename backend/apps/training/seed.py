def seed_exercises():
    from .models import Exercise

    existing = set(Exercise.objects.values_list("name", flat=True))
    Exercise.objects.bulk_create([
        Exercise(name=n, muscle_group=g, equipment=e, tracking=t, secondary_muscles=s)
        for n, g, e, t, s in BASE if n not in existing
    ])
